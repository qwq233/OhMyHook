#!/usr/bin/env python3

import argparse
import json
import os
import platform
import stat
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = REPO_ROOT / ".cargo" / "config.toml"
OWNERSHIP_MARKER = "# This file is auto-generated by scripts/setup_cargo_config.py."

ANDROID_TARGETS = (
    ("aarch64-linux-android", "aarch64-linux-android"),
    ("armv7-linux-androideabi", "armv7a-linux-androideabi"),
    ("i686-linux-android", "i686-linux-android"),
    ("x86_64-linux-android", "x86_64-linux-android"),
)


@dataclass(frozen=True)
class ConfigState:
    destination: Path
    content: str | None
    mode: int | None
    identity: tuple[int, int] | None


def is_ndk_root(path: Path) -> bool:
    return (path / "toolchains" / "llvm" / "prebuilt").is_dir()


def require_ndk_root(path: Path, source: str) -> Path:
    if not is_ndk_root(path):
        raise FileNotFoundError(f"Android NDK from {source} is invalid: {path}")
    return path.resolve()


def unique_paths(paths: list[Path]) -> list[Path]:
    return list(dict.fromkeys(path.resolve() for path in paths))


def detect_ndk_root(cli_value: str | None) -> Path:
    if cli_value:
        return require_ndk_root(Path(cli_value).expanduser(), "--ndk-root")

    env_candidates = []
    for env_name in ("ANDROID_NDK_ROOT", "ANDROID_NDK_HOME"):
        env_value = os.environ.get(env_name)
        if env_value:
            env_candidates.append(
                require_ndk_root(Path(env_value).expanduser(), env_name)
            )
    env_candidates = unique_paths(env_candidates)
    if len(env_candidates) > 1:
        raise RuntimeError(
            "ANDROID_NDK_ROOT and ANDROID_NDK_HOME select different NDKs; "
            "pass --ndk-root explicitly."
        )
    if env_candidates:
        return env_candidates[0]

    sdk_roots = []
    for env_name in ("ANDROID_HOME", "ANDROID_SDK_ROOT"):
        env_value = os.environ.get(env_name)
        if env_value:
            sdk_roots.append(Path(env_value).expanduser())
    sdk_roots.extend(
        (
            Path.home() / "Android" / "Sdk",
            Path.home() / "Library" / "Android" / "sdk",
            Path.home() / "AppData" / "Local" / "Android" / "Sdk",
            Path("/opt/android-sdk"),
            Path("/usr/local/lib/android/sdk"),
            Path("/mnt/d/android-sdk"),
        )
    )

    candidates = []
    for sdk_root in dict.fromkeys(sdk_roots):
        ndk_dir = sdk_root / "ndk"
        if ndk_dir.is_dir():
            candidates.extend(path for path in ndk_dir.iterdir() if is_ndk_root(path))
        bundled = sdk_root / "ndk-bundle"
        if is_ndk_root(bundled):
            candidates.append(bundled)
    candidates = unique_paths(candidates)
    if len(candidates) > 1:
        choices = "\n  ".join(str(path) for path in candidates)
        raise RuntimeError(
            "Multiple Android NDKs were found; pass --ndk-root explicitly:\n  "
            f"{choices}"
        )
    if candidates:
        return candidates[0]

    raise FileNotFoundError(
        "Android NDK not found. Install it under a standard Android SDK path, "
        "set ANDROID_NDK_ROOT/ANDROID_NDK_HOME, or pass --ndk-root."
    )


def guess_host_tags() -> list[str]:
    system = platform.system().lower()
    machine = platform.machine().lower()

    if system == "linux":
        if machine in ("x86_64", "amd64"):
            return ["linux-x86_64"]
        if machine in ("aarch64", "arm64"):
            return ["linux-aarch64"]
        raise RuntimeError(f"Unsupported Linux host architecture: {platform.machine()}")

    if system == "darwin":
        tags = []
        if machine in ("arm64", "aarch64"):
            tags.append("darwin-arm64")
        tags.append("darwin-x86_64")
        return tags

    if system == "windows":
        return ["windows-x86_64"]

    raise RuntimeError(f"Unsupported host platform: {platform.system()} {platform.machine()}")


def resolve_host_tag(ndk_root: Path, cli_value: str | None) -> str:
    prebuilt_dir = ndk_root / "toolchains" / "llvm" / "prebuilt"
    if cli_value:
        candidate = prebuilt_dir / cli_value
        if candidate.is_dir():
            return cli_value
        raise FileNotFoundError(f"NDK host tag does not exist: {candidate}")

    for tag in guess_host_tags():
        if (prebuilt_dir / tag).is_dir():
            return tag

    available = sorted(path.name for path in prebuilt_dir.iterdir() if path.is_dir())
    raise FileNotFoundError(
        "Unable to detect a matching NDK host tag. "
        f"Available tags: {', '.join(available) or '(none)'}"
    )


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False).replace("\x7f", "\\u007f")


def render_config(ndk_root: Path, host_tag: str, api_level: int) -> str:
    bin_dir = ndk_root / "toolchains" / "llvm" / "prebuilt" / host_tag / "bin"
    exe_suffix = ".cmd" if host_tag.startswith("windows-") else ""
    lines = [
        OWNERSHIP_MARKER,
        f"# NDK root: {toml_string(str(ndk_root))[1:-1]}",
        f"# Host tag: {toml_string(host_tag)[1:-1]}",
        f"# API level: {api_level}",
        "",
    ]

    for rust_target, clang_target in ANDROID_TARGETS:
        clang = bin_dir / f"{clang_target}{api_level}-clang{exe_suffix}"
        if not clang.is_file():
            raise FileNotFoundError(f"Required NDK tool not found: {clang}")
        lines.extend(
            [
                f"[target.{rust_target}]",
                f"linker = {toml_string(str(clang))}",
                "",
            ]
        )

    return "\n".join(lines)


def read_owned_config(output_path: Path) -> ConfigState:
    if output_path.is_symlink():
        try:
            destination = output_path.resolve(strict=True)
        except FileNotFoundError as exc:
            raise RuntimeError(f"output is a dangling symlink: {output_path}") from exc
    else:
        destination = output_path

    try:
        with destination.open("r", encoding="utf-8") as existing_file:
            file_stat = os.fstat(existing_file.fileno())
            if not stat.S_ISREG(file_stat.st_mode):
                raise RuntimeError(f"output is not a regular file: {output_path}")
            existing = existing_file.read()
        if not os.path.samestat(file_stat, destination.stat()):
            raise RuntimeError(f"output changed while being read: {output_path}")
    except FileNotFoundError:
        if output_path.is_symlink():
            raise RuntimeError(f"output symlink changed while being read: {output_path}")
        return ConfigState(destination, None, None, None)

    if existing.splitlines()[:1] != [OWNERSHIP_MARKER]:
        raise RuntimeError(f"refusing to overwrite non-generated config: {output_path}")
    return ConfigState(
        destination,
        existing,
        stat.S_IMODE(file_stat.st_mode),
        (file_stat.st_dev, file_stat.st_ino),
    )


def write_config(state: ConfigState, rendered: str) -> None:
    destination = state.destination
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=destination.parent,
            prefix=f".{destination.name}.",
            suffix=".tmp",
            delete=False,
        ) as temporary:
            temporary_path = Path(temporary.name)
            temporary.write(rendered)
        if state.mode is not None:
            os.chmod(temporary_path, state.mode)
        if state.identity is None:
            try:
                os.link(temporary_path, destination)
            except FileExistsError as exc:
                raise RuntimeError(f"output was created concurrently: {destination}") from exc
            temporary_path.unlink()
            temporary_path = None
        else:
            with destination.open("r", encoding="utf-8") as existing_file:
                file_stat = os.fstat(existing_file.fileno())
                existing = existing_file.read()
            if (
                not stat.S_ISREG(file_stat.st_mode)
                or (file_stat.st_dev, file_stat.st_ino) != state.identity
                or existing != state.content
            ):
                raise RuntimeError(f"output changed before it could be replaced: {destination}")
            os.replace(temporary_path, destination)
            temporary_path = None
    finally:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate .cargo/config.toml for Android NDK builds."
    )
    parser.add_argument("--ndk-root", help="Path to the Android NDK root.")
    parser.add_argument(
        "--host-tag",
        help="NDK host tag, for example linux-x86_64 or darwin-x86_64.",
    )
    parser.add_argument(
        "--api-level",
        type=int,
        default=21,
        help="Android API level embedded in clang wrapper names. Default: 21.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="Output file path. Default: .cargo/config.toml",
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--stdout",
        action="store_true",
        help="Print the generated config instead of writing a file.",
    )
    mode.add_argument(
        "--check",
        action="store_true",
        help="Verify that the generated config is current without writing it.",
    )
    mode.add_argument(
        "--force",
        action="store_true",
        help="Update an existing config generated by this script.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()

    try:
        ndk_root = detect_ndk_root(args.ndk_root)
        host_tag = resolve_host_tag(ndk_root, args.host_tag)
        rendered = render_config(ndk_root, host_tag, args.api_level)
    except (OSError, RuntimeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if args.stdout:
        sys.stdout.write(rendered)
        return 0

    output_path = args.output.expanduser()
    try:
        state = read_owned_config(output_path)
        if state.content == rendered:
            print(f"up-to-date: {output_path}")
            return 0
        if args.check:
            reason = "does not exist" if state.content is None else "is out of date"
            print(f"error: {output_path} {reason}", file=sys.stderr)
            return 1
        if state.content is not None and not args.force:
            print(
                f"error: {output_path} is out of date. Use --force to update it.",
                file=sys.stderr,
            )
            return 1
        output_path.parent.mkdir(parents=True, exist_ok=True)
        write_config(state, rendered)
    except (OSError, RuntimeError) as exc:
        action = "check" if args.check else "write"
        print(f"error: unable to {action} {output_path}: {exc}", file=sys.stderr)
        return 1
    print(f"wrote {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
